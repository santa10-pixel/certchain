'use client';

import { useState } from 'react';
import { VerificationService, VerificationResult } from '@/lib/services/VerificationService';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Label } from '@/components/ui/label';
import { SearchCheck, ShieldAlert, ShieldCheck, Lock, Activity, Link2 } from 'lucide-react';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';

export default function VerifierDashboard() {
  const [payloadStr, setPayloadStr] = useState('');
  const [isOffline, setIsOffline] = useState(false);
  const [result, setResult] = useState<VerificationResult | null>(null);
  const [loading, setLoading] = useState(false);
  const [parsedClaims, setParsedClaims] = useState<{ claims: any, hidden: any } | null>(null);

  const handleVerify = async () => {
    setLoading(true);
    setResult(null);
    setParsedClaims(null);
    
    try {
      const p = JSON.parse(payloadStr);
      setParsedClaims({ claims: p.claims, hidden: p.hidden });
    } catch(e) {}

    setTimeout(async () => {
      const srv = new VerificationService();
      const res = await srv.verify(payloadStr, isOffline);
      setResult(res);
      setLoading(false);
    }, 600); // Simulate network delay
  };

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      <div className="text-center mb-8">
        <div className="w-16 h-16 rounded-full bg-orange-500/20 flex items-center justify-center border border-orange-500/30 mx-auto mb-4">
          <SearchCheck className="w-8 h-8 text-orange-500" />
        </div>
        <h2 className="text-3xl font-bold tracking-tight">Verifier Portal</h2>
        <p className="text-slate-400 mt-2">Verify cryptographic proofs and Merkle commitments.</p>
      </div>

      <div className="grid md:grid-cols-2 gap-6">
        <Card className="bg-slate-900 border-slate-800">
          <CardHeader>
            <CardTitle>Verification Input</CardTitle>
            <CardDescription>Paste the secure payload generated by the student.</CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            <div className="space-y-2">
              <Label>Secure Payload (JSON)</Label>
              <textarea 
                className="w-full h-32 bg-slate-950 border border-slate-800 rounded-lg p-3 text-xs font-mono text-indigo-300 focus:ring-1 focus:ring-indigo-500 outline-none"
                value={payloadStr}
                onChange={e => setPayloadStr(e.target.value)}
                placeholder='{"id":"CERT-...", "claims":{}, ...}'
              />
            </div>
            
            <div className="flex items-center gap-2 p-3 bg-slate-950 rounded-lg border border-slate-800">
              <input type="checkbox" id="offline" checked={isOffline} onChange={e => setIsOffline(e.target.checked)} className="rounded border-slate-700 bg-slate-900" />
              <Label htmlFor="offline" className="cursor-pointer">Simulate Offline Mode (Infrastructure Down)</Label>
            </div>

            <Button 
              className="w-full bg-orange-600 hover:bg-orange-700" 
              onClick={handleVerify} 
              disabled={loading || !payloadStr}
            >
              {loading ? 'Verifying Cryptography...' : 'Verify Authenticity'}
            </Button>
          </CardContent>
        </Card>

        <Card className="bg-slate-900 border-slate-800">
          <CardHeader>
            <CardTitle>Verification Result</CardTitle>
          </CardHeader>
          <CardContent>
            {!result && !loading && (
              <div className="h-48 flex items-center justify-center text-slate-500 border border-dashed border-slate-800 rounded-lg">
                Submit a payload to verify.
              </div>
            )}
            
            {loading && (
              <div className="h-48 flex flex-col items-center justify-center text-slate-400 space-y-4">
                <Activity className="w-8 h-8 animate-spin text-indigo-500" />
                <p>Reconstructing Merkle Root...</p>
              </div>
            )}

            {result && (
              <div className="space-y-6 animate-in fade-in zoom-in duration-300">
                <div className={`p-4 rounded-xl flex gap-4 items-start ${result.success ? 'bg-green-500/10 border border-green-500/30' : 'bg-red-500/10 border border-red-500/30'}`}>
                  {result.success ? <ShieldCheck className="w-8 h-8 text-green-500 shrink-0" /> : <ShieldAlert className="w-8 h-8 text-red-500 shrink-0" />}
                  <div>
                    <h3 className={`text-xl font-bold ${result.success ? 'text-green-500' : 'text-red-500'}`}>{result.statusText}</h3>
                    <p className="text-sm text-slate-300 mt-1">{result.message}</p>
                    <div className="flex gap-2 mt-2 text-xs font-mono">
                      <span className="px-2 py-1 bg-slate-950 rounded text-slate-400">{result.mode}</span>
                      <span className="px-2 py-1 bg-slate-950 rounded text-slate-400">{result.latencyMs}ms latency</span>
                    </div>
                  </div>
                </div>

                {parsedClaims && (
                  <Tabs defaultValue="claims" className="w-full">
                    <TabsList className="w-full grid grid-cols-2 bg-slate-950">
                      <TabsTrigger value="claims">Disclosed Claims</TabsTrigger>
                      <TabsTrigger value="technical">Technical Proof</TabsTrigger>
                    </TabsList>
                    <TabsContent value="claims" className="space-y-2 mt-4">
                      {Object.keys(parsedClaims.claims).map(k => (
                        <div key={k} className="flex justify-between py-2 border-b border-slate-800">
                          <span className="capitalize text-slate-400">{k}</span>
                          <span className="font-medium">{parsedClaims.claims[k].val}</span>
                        </div>
                      ))}
                      {Object.keys(parsedClaims.hidden).map(k => (
                        <div key={k} className="flex justify-between py-2 border-b border-slate-800">
                          <span className="capitalize text-slate-500">{k}</span>
                          <span className="text-xs text-amber-500 flex items-center gap-1"><Lock className="w-3 h-3"/> ZK Hidden</span>
                        </div>
                      ))}
                    </TabsContent>
                    <TabsContent value="technical" className="mt-4">
                       <div className="bg-slate-950 p-4 rounded-lg border border-slate-800 text-xs font-mono space-y-3 break-all text-slate-400">
                         <div><span className="text-slate-500 mb-1 block">Blockchain Anchor:</span><span className="text-indigo-400">{result.blockchainTx}</span></div>
                         {result.threatDetected && (
                           <div><span className="text-slate-500 mb-1 block">Security Event:</span><span className="text-red-400">{result.threatDetected}</span></div>
                         )}
                       </div>
                    </TabsContent>
                  </Tabs>
                )}
              </div>
            )}
          </CardContent>
        </Card>
      </div>
    </div>
  );
}
